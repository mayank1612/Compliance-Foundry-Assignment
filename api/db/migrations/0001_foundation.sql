-- =============================================================================
-- 0001_foundation.sql — request role, `app` schema, shared trigger helpers
-- =============================================================================
-- Schema v1 (Task 1.1). Frozen once reviewed: fixes ship as new migrations.
--
-- What: the primitives every later migration builds on; no domain tables here.
-- Why:  keeping infrastructure out of the table migrations lets 0002–0004 read
--       as pure data modelling, and 0005 as pure access control.
--
-- Conventions used throughout the schema (explained once, here):
--   * Primary keys are `uuid DEFAULT uuidv7()` (built into Postgres 18). v7 UUIDs
--     start with a millisecond timestamp, so new rows land at the right-hand edge
--     of the B-tree (like a bigserial, no random page splits as with v4), yet they
--     are globally unique, safe to expose in URLs (no "you are customer #312"
--     leakage) and can be generated by clients for optimistic UI.
--   * Every tenant-owned row carries `organization_id`, even when it is derivable
--     through a parent. Composite foreign keys (organization_id, parent_id) then
--     make a cross-tenant reference impossible, and row-level security (0005) can
--     filter every table without joins.
--   * Timestamps are `timestamptz` (an instant); due dates are `date` (a calendar
--     day with no zone — "due on the 20th" must not shift with the viewer's zone).
--   * Lengths and formats are CHECK constraints, so every writer (API, scripts,
--     a future service) gets the same validation as the GraphQL layer.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- Request role: app_user
-- -----------------------------------------------------------------------------
-- Every API request runs inside one transaction that begins with
--     SET LOCAL ROLE app_user;
--     SELECT set_config('app.user_id', '<authenticated user uuid>', true);
-- app_user owns no tables, so row-level security policies (0005) always apply to
-- it. The schema owner (the role running these migrations) bypasses RLS; it is
-- used only by migrations, seeds and the SECURITY DEFINER functions below.
-- In production the API would log in as a role that is a member of app_user.
--
-- Roles are cluster-wide objects (shared by every database on the server), so
-- this is "create if missing" instead of a plain CREATE ROLE.
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'app_user') THEN
    CREATE ROLE app_user NOLOGIN;
  END IF;
END
$$;


-- -----------------------------------------------------------------------------
-- `app` schema: infrastructure functions (auth helpers, trigger functions)
-- -----------------------------------------------------------------------------
-- Keeps `public` = data only, which is also exactly what kysely-codegen turns
-- into TypeScript types.
-- Only roles granted USAGE on it (app_user, in 0005) can reach its functions, and
-- 0005 also revokes the default PUBLIC execute right, granting back only what
-- app_user needs.
CREATE SCHEMA app;


-- -----------------------------------------------------------------------------
-- app.current_user_id() — who is making this request?
-- -----------------------------------------------------------------------------
-- Reads the transaction-local setting written at the start of each request.
-- `true` = return NULL instead of erroring when the setting was never set.
-- `nullif(…, '')`: once a custom setting has been used in a session, Postgres
-- reports it as '' (not NULL) after that transaction ends, and ''::uuid would
-- throw. Verified in api/test/db.test.ts — this keeps "no user" = NULL, which
-- every policy treats as "sees nothing" (fail closed).
-- Also used as a column DEFAULT (tasks.created_by, …) so authorship cannot be
-- spoofed: app_user is not granted INSERT on those columns (0005).
CREATE FUNCTION app.current_user_id() RETURNS uuid
LANGUAGE sql STABLE PARALLEL SAFE
AS $$
  SELECT nullif(pg_catalog.current_setting('app.user_id', true), '')::uuid
$$;


-- -----------------------------------------------------------------------------
-- app.set_updated_at() — keeps `updated_at` honest
-- -----------------------------------------------------------------------------
-- BEFORE UPDATE trigger body shared by every table with an `updated_at` column.
-- Doing it in the database means no code path can forget it. `now()` is the
-- transaction start time, so all rows changed in one request share a timestamp.
CREATE FUNCTION app.set_updated_at() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := pg_catalog.now();
  RETURN NEW;
END
$$;
